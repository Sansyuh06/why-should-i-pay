// =============================================================================
// HELPER FUNCTIONS
// =============================================================================
export function getProblemById(id: string): DatabaseProblem | undefined {
  return allDatabaseProblems.find(p => p.id === id);
}

export function getProblemsByTopic(topic: string): DatabaseProblem[] {
  return allDatabaseProblems.filter(p =>
    p.topic === topic ||
    p.categories.some(c => c.toLowerCase() === topic.toLowerCase())
  );
}

export function getProblemsByDifficulty(difficulty: 'easy' | 'medium' | 'hard'): DatabaseProblem[] {
  return allDatabaseProblems.filter(p => p.difficulty === difficulty);
}

export function searchProblems(query: string): DatabaseProblem[] {
  const lower = query.toLowerCase();
  return allDatabaseProblems.filter(p =>
    p.title.toLowerCase().includes(lower) ||
    p.description.toLowerCase().includes(lower) ||
    p.categories.some(c => c.toLowerCase().includes(lower)) ||
    p.tags.some(t => t.toLowerCase().includes(lower)) ||
    p.companies.some(c => c.toLowerCase().includes(lower))
  );
}

export function getAllTopics(): string[] {
  const topics = new Set<string>();
  allDatabaseProblems.forEach(p => {
    p.categories.forEach(c => topics.add(c));
  });
  return Array.from(topics).sort();
}

export function getAllCompanies(): string[] {
  const companies = new Set<string>();
  allDatabaseProblems.forEach(p => {
    p.companies.forEach(c => companies.add(c));
  });
  return Array.from(companies).sort();
}

